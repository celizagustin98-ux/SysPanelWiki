-- QR en campo: ubicación física, estado de etiquetas, auditorías físicas, escaneos, PIN y ajustes (idempotente)

-- ── Ubicación física dentro del sector y etiqueta ───────────────────────
alter table inventario add column if not exists ubicacion_detalle text;      -- puesto, escritorio, rack, posición
alter table inventario add column if not exists etiqueta_impresa_at timestamptz;
alter table inventario add column if not exists etiqueta_reimprimir boolean not null default false;
create index if not exists inventario_etiqueta_idx on inventario (etiqueta_impresa_at) where etiqueta_impresa_at is null;
create index if not exists inventario_sector_idx on inventario (sector);

-- ── Códigos preimpresos (etiquetas en blanco para dar de alta al escanear) ─
create table if not exists inventario_etiquetas_libres (
  codigo text primary key,
  lote text,
  impresa_at timestamptz,
  usada_at timestamptz,
  inventario_id uuid references inventario(id) on delete set null,
  created_by_nombre text,
  created_at timestamptz not null default now()
);

-- ── Auditorías físicas (relevamiento por sector escaneando) ──────────────
create table if not exists inventario_auditorias (
  id uuid primary key default gen_random_uuid(),
  numero int generated by default as identity,
  nombre text not null,
  planta text,
  sector text,
  estado text not null default 'abierta' check (estado in ('abierta', 'cerrada')),
  notas text,
  esperados int not null default 0,
  creada_por uuid references app_users(id) on delete set null,
  creada_por_nombre text,
  created_at timestamptz not null default now(),
  cerrada_at timestamptz,
  cerrada_por_nombre text
);
create index if not exists inventario_auditorias_estado_idx on inventario_auditorias (estado, created_at desc);

create table if not exists inventario_auditoria_items (
  id uuid primary key default gen_random_uuid(),
  auditoria_id uuid not null references inventario_auditorias(id) on delete cascade,
  inventario_id uuid references inventario(id) on delete set null,
  codigo text not null,
  -- encontrado: estaba donde figura · otro_lugar: figura en otro sector · desconocido: código sin activo
  resultado text not null check (resultado in ('encontrado', 'otro_lugar', 'desconocido')),
  sector_registrado text,
  ubicacion_detalle text,
  observacion text,
  escaneado_por_nombre text,
  escaneado_at timestamptz not null default now(),
  unique (auditoria_id, codigo)
);
create index if not exists inventario_auditoria_items_aud_idx on inventario_auditoria_items (auditoria_id, escaneado_at desc);

-- ── Historial de escaneos ───────────────────────────────────────────────
create table if not exists inventario_escaneos (
  id uuid primary key default gen_random_uuid(),
  inventario_id uuid references inventario(id) on delete cascade,
  codigo text,
  user_id uuid references app_users(id) on delete set null,
  usuario_nombre text,
  accion text not null default 'ver',
  detalle text,
  publico boolean not null default false,
  created_at timestamptz not null default now()
);
create index if not exists inventario_escaneos_item_idx on inventario_escaneos (inventario_id, created_at desc);

-- ── PIN corto para confirmar escaneos ───────────────────────────────────
alter table app_users add column if not exists qr_pin_hash text;

-- ── Ajustes del QR ──────────────────────────────────────────────────────
-- qr_pedir_clave: 'siempre' | 'turno' (cada 8 h) | 'nunca'
alter table app_settings add column if not exists qr_pedir_clave text not null default 'turno';
alter table app_settings add column if not exists qr_reporte_publico boolean not null default true;
alter table app_settings add column if not exists etiqueta_ancho_mm int not null default 57;
-- Dirección que se imprime en el QR (ej. https://172.20.1.134:3443). Vacía = la dirección desde donde se imprime.
alter table app_settings add column if not exists qr_url_base text;

